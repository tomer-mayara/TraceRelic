import assert from "node:assert/strict";
import { appendFile, mkdir, readFile, unlink, writeFile } from "node:fs/promises";
import { basename, dirname, join } from "node:path";
import { test } from "node:test";
import { zstdCompressSync } from "node:zlib";
import { GlobalConfig } from "@tracerelic/collector/config";
import { LocalLLMHistory } from "@tracerelic/collector/history";
import { CodexHistory } from "@tracerelic/collector/providers";
import { LocalCollector } from "@tracerelic/collector/scan";
import { CodexRolloutFixture as Rollout } from "../../fixtures/codex-rollout-fixture.ts";
import { InMemoryCollectorStorage } from "../../fixtures/in-memory-collector-storage.ts";

for (const archived of [false, true]) test("compressed copies deduplicate by bytes and independent headers remain visible; archived = " + archived, async t => {
  const root = await Rollout.create();
  t.after(() => root.close());
  const at = "2026-02-01T00:00:00Z";
  const current = await root.write([Rollout.header("one"), Rollout.message(at, "Original")]);
  const archive = archived ? join(root.home, "archived_sessions") : dirname(current);
  await mkdir(archive, { recursive: true });
  const compressed = join(archive, basename(current) + ".zst");
  const reader = new CodexHistory(root.home);
  const history = async () => (await new LocalLLMHistory([reader]).readLocalHistory(new Date(at), new Date("2026-02-02"))).map(row => row.sourceFile);
  const sources = async () => (await Array.fromAsync(reader.discoverSources())).map(row => row.sessionId);
  await writeFile(compressed, zstdCompressSync(await readFile(current)));
  assert.deepEqual(await history(), [current]);
  assert.deepEqual(await sources(), ["one"]);
  await writeFile(compressed, zstdCompressSync(Buffer.from([Rollout.header("two"), Rollout.message(at, "Independent")].map(row => JSON.stringify(row)).join("\n") + "\n")));
  assert.deepEqual(await history(), [current, compressed]);
  assert.deepEqual(await sources(), ["one", "two"]);
});

test("compression keeps the logical Codex bytes, checkpoint and chat through restart", async t => {
  const root = await Rollout.create();
  t.after(() => root.close());
  const at = "2026-02-01T00:00:00Z";
  const file = await root.write([Rollout.header("one"), Rollout.message(at, "First")]);
  const config = new GlobalConfig(root.home, undefined, "desktop");
  const reader = new CodexHistory(config.codexPath);
  const storage = new InMemoryCollectorStorage();
  const scan = () => new LocalCollector(config, storage).scanOnce();
  await scan();
  const source = { harness: "codex", sessionId: "one", installationId: "desktop", streamId: basename(file) } as const;
  const checkpoint = await storage.readCheckpoint(source);
  const prefix = await readFile(file);
  await writeFile(file + ".zst", zstdCompressSync(prefix));
  const query = () => new LocalLLMHistory([reader]).readLocalHistory(new Date(at), new Date("2026-02-02"));
  assert.deepEqual((await query()).map(entry => entry.sourceFile), [file]);
  await unlink(file);
  assert.deepEqual((await query()).map(entry => entry.sourceFile), [file + ".zst"]);
  const [compressed] = await Array.fromAsync(reader.discoverSources());
  assert.equal(compressed.fileSize, prefix.length);
  assert.equal(await compressed.completeEnd(), prefix.length);
  assert.equal((await compressed.prefixDigests([prefix.length]))[0].prefixDigest, checkpoint.checkpoint?.prefixDigest);
  assert.deepEqual(await reader.confirmedAbsent([basename(file)]), []);
  const [unchanged] = await scan();
  assert.equal(unchanged.missingSources, undefined);
  assert.deepEqual(await storage.readCheckpoint(source), checkpoint);
  const suffix = Buffer.from(JSON.stringify(Rollout.message(at, "Café")) + "\n");
  await appendFile(file + ".zst", zstdCompressSync(suffix));
  assert.equal(await compressed.completeEnd(), prefix.length);
  const [updated] = await scan();
  assert.deepEqual(updated.messages.map(message => message.text), ["First", "Café"]);
  assert.equal((await storage.readCheckpoint(source)).checkpoint?.offset, prefix.length + suffix.length);
});

for (const longer of ["plain", "compressed"] as const) test("a compatible older copy does not rewind the longer " + longer + " rollout", async t => {
  const root = await Rollout.create();
  t.after(() => root.close());
  const at = "2026-02-01T00:00:00Z";
  const plain = await root.write([Rollout.header("one"), Rollout.message(at, "One")]);
  const short = await readFile(plain);
  const extra = Buffer.from(JSON.stringify(Rollout.message(at, "Two")) + "\n");
  await writeFile(plain + ".zst", zstdCompressSync(longer === "plain" ? short : Buffer.concat([short, extra])));
  if (longer === "plain") await appendFile(plain, extra);
  const config = new GlobalConfig(root.home, undefined, "desktop");
  const reader = new CodexHistory(config.codexPath);
  const chosen = longer === "plain" ? plain : plain + ".zst";
  assert.deepEqual((await new LocalLLMHistory([reader]).readLocalHistory(new Date(at), new Date("2026-02-02"))).map(row => row.sourceFile), [chosen, chosen]);
  assert.deepEqual((await Array.fromAsync(reader.discoverSources())).map(row => row.sourceFile), [chosen]);
  const storage = new InMemoryCollectorStorage();
  const scan = () => new LocalCollector(config, storage).scanOnce();
  const [view] = await scan();
  assert.deepEqual(view.messages.map(row => row.text), ["One", "Two"]);
  const key = { harness: "codex", sessionId: "one", streamId: basename(plain), installationId: "desktop" } as const;
  const snapshot = await storage.readCheckpoint(key);
  await scan();
  assert.deepEqual(await storage.readCheckpoint(key), snapshot);
});

test("a damaged replacement compressed frame is a changed capture and a stable bad frame reports a read error", async t => {
  const root = await Rollout.create();
  t.after(() => root.close());
  const plain = await root.write([Rollout.header("one"), { message: "visible" }]);
  const packed = zstdCompressSync(await readFile(plain));
  await writeFile(plain + ".zst", packed);
  await unlink(plain);
  const reader = new CodexHistory(root.home);
  const [captured] = await Array.fromAsync(reader.discoverSources());
  await writeFile(plain + ".zst", Buffer.alloc(packed.length + 50, 0xff));
  await assert.rejects(Array.fromAsync(captured.readBatches({ offset: 0, lineNumber: 0 })), { name: "TranscriptChangedError" });
  await assert.rejects(new LocalLLMHistory([reader]).readLocalHistory(new Date(0), new Date()));
  await writeFile(plain + ".zst", packed);
  const [healthy] = await Array.fromAsync(reader.discoverSources());
  assert.equal(healthy.sessionId, "one");
});
